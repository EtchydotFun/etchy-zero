// Writes src/idl.ts from the program's IDL (rune-pool/onchain/artifacts/rune_pool.json; M118: `next`
// reads artifacts/next/, a build not deployed yet: only ever a superset of the live interface).
// Run after every program build: node rune-pool/sdk/scripts/gen-idl.mjs [next]
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const here = import.meta.dirname;
const dir = process.argv[2] === 'next' ? 'next/' : '';
const idl = JSON.parse(readFileSync(join(here, `../../onchain/artifacts/${dir}rune_pool.json`), 'utf8'));
const out = `// Generated by scripts/gen-idl.mjs from the rune-pool program's IDL. Do not edit.
// prettier-ignore
export const RUNE_POOL_IDL = ${JSON.stringify(idl)} as const;
`;
writeFileSync(join(here, '../src/idl.ts'), out);
console.log(`src/idl.ts: ${idl.instructions.length} instructions, ${idl.accounts.length} accounts, ${idl.events.length} events`);
