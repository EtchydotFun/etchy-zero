// M118: writes src/miner-idl.ts from the rune-miner program's IDL (rune-pool/onchain/artifacts/next/
// rune_miner.json until it is deployed; then artifacts/rune_miner.json).
// Run after every miner build: node rune-pool/sdk/scripts/gen-miner-idl.mjs [next]
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const here = import.meta.dirname;
const dir = process.argv[2] === 'next' ? 'next/' : '';
const file = join(here, `../../onchain/artifacts/${dir}rune_miner.json`);
if (!existsSync(file)) throw new Error(`no ${file}`);
const idl = JSON.parse(readFileSync(file, 'utf8'));
const out = `// Generated by scripts/gen-miner-idl.mjs from the rune-miner program's IDL. Do not edit.
// prettier-ignore
export const RUNE_MINER_IDL = ${JSON.stringify(idl)} as const;
`;
writeFileSync(join(here, '../src/miner-idl.ts'), out);
console.log(`src/miner-idl.ts: ${idl.instructions.length} instructions, ${idl.accounts.length} accounts, ${idl.events.length} events`);
